-- One row per chat (General Chat, PDF Chat, Image Query, Text-to-Image).
create table if not exists public.sessions (
    id          text primary key,                 -- uuid4 generated by the backend
    title       text not null default 'New chat',
    mode        text not null default 'chat',     -- chat | pdf | image | generate
    created_at  text not null,                    -- ISO-8601 string from the backend
    updated_at  text not null,
    messages    jsonb not null default '[]',      -- [{role, content}, ...]
    session_id  text,                             -- linked faiss_indexes.session_id (PDF chats)
    documents   jsonb default '[]',               -- uploaded file names
    owner_id    text                              -- SHA-256 of the browser's X-Client-Id
);

-- One serialized FAISS index per PDF upload.
create table if not exists public.faiss_indexes (
    session_id  text primary key,                 -- upsert target
    index_b64   text not null,                    -- base64 pickle of index.faiss + index.pkl
    updated_at  text not null,
    owner_id    text                              -- SHA-256 of the browser's X-Client-Id
);

create index if not exists sessions_owner_updated_idx
    on public.sessions (owner_id, updated_at desc);

-- Only the backend touches these tables, with the secret (service_role) key,
-- which bypasses RLS. No policies, so the public keys get nothing.
alter table public.sessions      enable row level security;
alter table public.faiss_indexes enable row level security;
